def main():
    if not XLSX.exists():
        print(f"ERROR: not found {XLSX}", file=sys.stderr)
        sys.exit(1)

    wb = load_workbook(XLSX)
    added, skipped = [], []

    # --- 1) 日次ニュース に ジャンル列を追加（B列に挿入、既存行は「ゲーム」で埋める）---
    ws = wb["日次ニュース"]
    headers = [c.value for c in ws[1]]
    if "ジャンル" not in headers:
        ws.insert_cols(2)
        c = ws.cell(row=1, column=2, value="ジャンル")
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
        ws.column_dimensions["B"].width = 10
        n = 0
        for r in range(2, ws.max_row + 1):
            if any(ws.cell(row=r, column=col).value not in (None, "")
                   for col in range(1, ws.max_column + 1)):
                cc = ws.cell(row=r, column=2, value="ゲーム")
                cc.font = BODY_FONT
                cc.alignment = Alignment(vertical="top", wrap_text=True)
                cc.border = BORDER
                n += 1
        print(f"[日次ニュース] ジャンル列を追加、既存{n}行を『ゲーム』で backfill")
    else:
        print("[日次ニュース] ジャンル列は既にあり (skip)")

    # --- 2) 掘り下げ・分析 / 今後起きそうなこと に ジャンル列を末尾追加 ---
    for sheet_name in ["掘り下げ・分析", "今後起きそうなこと", "横断的問い"]:
        if sheet_name not in wb.sheetnames:
            continue
        ws2 = wb[sheet_name]
        hs = [c.value for c in ws2[1]]
        while hs and hs[-1] is None:
            hs.pop()
        if "ジャンル" in hs:
            print(f"[{sheet_name}] ジャンル列は既にあり (skip)")
            continue
        col = len(hs) + 1
        c = ws2.cell(row=1, column=col, value="ジャンル")
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
        ws2.column_dimensions[get_column_letter(col)].width = 12
        n = 0
        for r in range(2, ws2.max_row + 1):
            if any(ws2.cell(row=r, column=x).value not in (None, "") for x in range(1, col)):
                cc = ws2.cell(row=r, column=col, value="ゲーム")
                cc.font = BODY_FONT
                cc.alignment = Alignment(vertical="top", wrap_text=True)
                cc.border = BORDER
                n += 1
        print(f"[{sheet_name}] ジャンル列を末尾に追加、既存{n}行を backfill")

    # --- 2.5) 業界マトリクス に ジャンル列を追加（末尾）---
    if "業界マトリクス" in wb.sheetnames:
        wsm = wb["業界マトリクス"]
        hm = [c.value for c in wsm[1]]
        while hm and hm[-1] is None:
            hm.pop()
        for g in ["映画", "アニメ", "漫画", "小説", "音楽"]:
            if g in hm:
                continue
            col = len(hm) + 1
            c = wsm.cell(row=1, column=col, value=g)
            c.font = HEADER_FONT
            c.fill = PatternFill("solid", start_color=GENRE_FILL.get(g, "1F3864"))
            c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            c.border = BORDER
            wsm.column_dimensions[get_column_letter(col)].width = 30
            for r in range(2, wsm.max_row + 1):
                cc = wsm.cell(row=r, column=col)
                cc.font = BODY_FONT
                cc.alignment = Alignment(vertical="top", wrap_text=True)
                cc.border = BORDER
            hm.append(g)
            print(f"[業界マトリクス] 列『{g}』を追加")

    # --- 3) 新規シートを追加 ---
    for name, hdrs, widths, genre, rows in NEW_SHEETS:
        if name in wb.sheetnames:
            skipped.append(name)
            continue
        ws3 = wb.create_sheet(name)
        mkheaders(ws3, hdrs, widths, GENRE_FILL.get(genre, "1F3864"))
        if rows:
            seed(ws3, rows)
        added.append(name)

    wb.save(XLSX)

    print(f"\n追加したシート ({len(added)}):")
    for a in added:
        print(f"  + {a}")
    if skipped:
        print(f"\n既存のためスキップ ({len(skipped)}):")
        for s in skipped:
            print(f"  = {s}")
    print(f"\n合計シート数: {len(wb.sheetnames)}")


if __name__ == "__main__":
    main()
